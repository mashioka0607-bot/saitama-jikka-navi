"""Keep the prefecture-wide diagnosis from sending non-Kawagoe users to Kawagoe-only services."""
from pathlib import Path

path = Path(__file__).resolve().parents[1] / "build.py"
source = path.read_text(encoding="utf-8")

changes = [
    ("川越市の無料相談も使い、名義・家族の意向・維持費・売却/活用の選択肢を1枚に整理する。",
     "埼玉県の空き家コーディネーター等も使い、名義・家族の意向・維持費・売却/活用の選択肢を1枚に整理する。"),
    ("遠方なら川越市の空き家管理連携先も確認する。",
     "遠方なら所在地の市町村で空き家管理の相談先を確認する。"),
    ('href="https://www.city.kawagoe.saitama.jp/kurashi/jyutaku/1003031/1020433.html">川越市公式：空き家・空き地の相談窓口',
     'href="https://www.pref.saitama.lg.jp/a1106/akiya/r7_akiyacoodinator.html">埼玉県公式：空き家コーディネーター（原則無料）'),
    ('href="https://www.city.kawagoe.saitama.jp/kurashi/jyutaku/1003031/1003044.html">川越市公式：シルバー人材センターとの空き家管理連携',
     'href="https://www.pref.saitama.lg.jp/a1106/akiyakanrisyatouroku.html">埼玉県公式：空き家の持ち主応援隊（管理相談）'),
    ("川越市の相談先を整理します。", "埼玉県の公的相談先を整理します。"),
]
changed = 0
for old, new in changes:
    n = source.count(old)
    if n == 1:
        source = source.replace(old, new, 1)
        changed += 1
    elif n == 0 and source.count(new) == 1:
        continue
    else:
        raise SystemExit(f"Unexpected diagnosis source state: {old[:80]} (old={n}, new={source.count(new)})")

if changed:
    path.write_text(source, encoding="utf-8")
print(f"Prefecture-wide diagnosis source patch: {changed} replacements")

# Static diagnosis is generated by build.py after this patch runs.
